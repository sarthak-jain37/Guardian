"""Integration surfaces; this phase supplies local test adapters, not backend services."""

from typing import Protocol

from .contracts import AnalysisRequest, ApprovalDecision, ContextLookup, EvidenceBundle, Proposal, RevisionRequest
from .modeling import ModelConfig, ModelResult
from .evidence_tools import ToolResult
from .governance import GovernedDecision


class EvidencePort(Protocol):
    def load(self, request: AnalysisRequest) -> EvidenceBundle: ...
    def current(self, request: AnalysisRequest) -> EvidenceBundle: ...
    def fetch_context(self, request: AnalysisRequest, lookup: ContextLookup) -> EvidenceBundle: ...
    def lookup(self, request: AnalysisRequest, lookup: ContextLookup, *, timeout_seconds: float) -> ToolResult: ...


class ModelClient(Protocol):
    producer: str
    def generate(self, stage: str, messages: list[dict], output_schema: dict, config: ModelConfig,
                 *, timeout_seconds: float) -> ModelResult: ...


class BudgetPort(Protocol):
    def model_call_count(self, run_id: str) -> int: ...
    def reserve_model_call(self, run_id: str, stage: str, limit: int, repair: bool = False) -> int: ...
    def model_repair_count(self, run_id: str, stage: str) -> int: ...
    def reserve_lookup_batch(self, run_id: str, batch_key: str, requests: list[dict], rounds: int, calls: int) -> dict: ...
    def begin_lookup(self, batch_key: str, index: int) -> dict | None: ...
    def complete_lookup(self, batch_key: str, index: int, result: dict) -> None: ...
    def begin_action(self, action_key: str) -> bool: ...


class ReviewPort(Protocol):
    authoritative: bool
    def publish(self, proposal: Proposal, report: dict) -> Proposal: ...
    def get_proposal(self, proposal_id: str) -> Proposal: ...
    def get_decision(self, decision_id: str) -> ApprovalDecision | GovernedDecision: ...
    def finalize_run(self, run_id: str, result: dict) -> dict: ...
    def publish_report(self, run_id: str, report: dict) -> dict: ...
    def get_report(self, run_id: str) -> dict: ...
    def get_proposal_status(self, proposal_id: str) -> str: ...
    def project_proposal(self, proposal_id: str, status: str, reason: str | None) -> dict: ...
    def get_proposal_decision(self, proposal_id: str) -> ApprovalDecision | None: ...
    def request_revision(self, request: RevisionRequest) -> RevisionRequest: ...
    def get_revision(self, revision_request_id: str) -> RevisionRequest: ...
    def get_successor(self, proposal_id: str) -> RevisionRequest | None: ...


class VerificationPort(Protocol):
    simulation_only: bool
    def check(self, evidence: EvidenceBundle, result_rules: list[dict]) -> list[dict]: ...
    def check_adoption(self, evidence: EvidenceBundle) -> list[dict]: ...


class BaselinePort(Protocol):
    """Backend owns the governed adoption transaction; the graph supplies IDs."""
    simulation_only: bool
    def adopt_approved_snapshot(self, proposal_id: str, decision_id: str, action_key: str) -> dict: ...


class ExecutionPort(Protocol):
    simulation_only: bool
    def request(self, proposal_id: str, decision_id: str, action_key: str) -> dict: ...
