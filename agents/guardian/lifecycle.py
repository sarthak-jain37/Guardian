    ACTIVE = "ACTIVE"
    SUPERSEDED = "SUPERSEDED"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    REJECTED = "REJECTED"
    BROKEN_ROLLBACK = "BROKEN_ROLLBACK"


