    ANALYZING = "ANALYZING"
    WAITING_FOR_CONTEXT = "WAITING_FOR_CONTEXT"
    PENDING_REVIEW = "PENDING_REVIEW"
    EXECUTION_REQUESTED = "EXECUTION_REQUESTED"
    VERIFYING = "VERIFYING"
    COMPLETED = "COMPLETED"
    NO_CHANGE = "NO_CHANGE"
    REJECTED = "REJECTED"
    STALE = "STALE"
    BLOCKED = "BLOCKED"
    FAILED = "FAILED"
    ROLLED_BACK = "ROLLED_BACK"
    NEEDS_MANUAL_INTERVENTION = "NEEDS_MANUAL_INTERVENTION"
